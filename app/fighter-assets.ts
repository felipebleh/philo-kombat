export const fighterThumbnailArt = (fighter: string) =>
  FIGHTER_THUMBNAILS[fighter] ?? FIGHTER_THUMBNAILS.plato;

export const fightAssetUrls = (player: string, opponent: string, arena = FIGHTER_ARENAS[player]) =>
  Array.from(
    new Set([
      ...(FIGHTER_ASSETS[player] ?? []),
      ...(FIGHTER_ASSETS[opponent] ?? []),
      arena,
      "/game/victory-spritesheet.webp",
    ].filter(Boolean)),
  );

export async function preloadFightAssets(
  player: string,
  opponent: string,
  onProgress?: (progress: number) => void,
  arena?: string,
) {
  const urls = fightAssetUrls(player, opponent, arena);
  let completed = 0;

  await Promise.all(
    urls.map(
      (src) =>
        new Promise<void>((resolve) => {
          const image = new window.Image();
          let settled = false;
          const finish = () => {
            if (settled) return;
            settled = true;
            completed += 1;
            onProgress?.(completed / urls.length);
            resolve();
          };
          image.decoding = "async";
          image.onload = finish;
          image.onerror = finish;
          image.src = src;
          if (image.complete) queueMicrotask(finish);
        }),
    ),
  );
}
